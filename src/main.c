static void set_differential_velocity(float linear, float angular)
{
    float v_left = linear - (angular * WHEEL_BASE_M * 0.5f);
    float v_right = linear + (angular * WHEEL_BASE_M * 0.5f);

    // Convert to PWM values for your hardware; clamp to [0, MAX_SPEED_MPS]
    if (v_left > MAX_SPEED_MPS)
        v_left = MAX_SPEED_MPS;
    if (v_right > MAX_SPEED_MPS)
        v_right = MAX_SPEED_MPS;
    if (v_left < -MAX_SPEED_MPS)
        v_left = -MAX_SPEED_MPS;
    if (v_right < -MAX_SPEED_MPS)
        v_right = -MAX_SPEED_MPS;

    // Map speeds to PWM duty cycles (0-100%)
    uint32_t left_pwm = (uint32_t)((fabsf(v_left) / MAX_SPEED_MPS) * (__HAL_TIM_GET_AUTORELOAD(&htim3)));
    uint32_t right_pwm = (uint32_t)((fabsf(v_right) / MAX_SPEED_MPS) * (__HAL_TIM_GET_AUTORELOAD(&htim3)));

    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, left_pwm);
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, right_pwm);

    // TODO: Control motor direction pins based on sign of v_left and v_right
}

